#!/usr/bin/env node
// Generates src/features/fonts/catalog.generated.ts from scripts/fonts.config.json and the metadata
// shipped in each @fontsource package. Loaders are emitted as literal dynamic imports because Vite
// can only code-split imports whose package paths are known at build time.
//
//   node scripts/gen-font-catalog.mjs          write the catalog
//   node scripts/gen-font-catalog.mjs --check  fail if the committed catalog is out of date
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src/features/fonts/catalog.generated.ts');
const config = JSON.parse(readFileSync(join(root, 'scripts/fonts.config.json'), 'utf8'));
const errors = [];

function readMetadata(pkg) {
  const file = join(root, 'node_modules', pkg, 'metadata.json');
  if (!existsSync(file)) {
    errors.push(`${pkg}: not installed`);
    return null;
  }
  return JSON.parse(readFileSync(file, 'utf8'));
}

function familyFromCss(pkg, cssFile) {
  const css = readFileSync(join(root, 'node_modules', pkg, cssFile), 'utf8');
  return /font-family:\s*'([^']+)'/.exec(css)?.[1] ?? null;
}

const entries = [];
const seen = new Set();
for (const font of config.fonts) {
  if (seen.has(font.id)) errors.push(`${font.id}: duplicate id`);
  seen.add(font.id);

  const pkg = `${font.variable ? '@fontsource-variable' : '@fontsource'}/${font.id}`;
  const meta = readMetadata(pkg);
  if (!meta) continue;

  const scripts = ['arabic', 'latin'].filter((s) => meta.subsets.includes(s));
  if (!scripts.length) errors.push(`${font.id}: neither an arabic nor a latin subset`);
  if (
    font.category !== 'sans' &&
    font.category !== 'serif' &&
    font.category !== 'mono' &&
    !meta.subsets.includes('arabic')
  ) {
    errors.push(`${font.id}: Arabic category "${font.category}" without an arabic subset`);
  }

  let family;
  let loaders;
  let variable = null;
  if (font.variable) {
    const wght = meta.variable?.wght;
    if (!wght) {
      errors.push(`${font.id}: variable package without a wght axis`);
      continue;
    }
    if (!existsSync(join(root, 'node_modules', pkg, 'wght.css'))) errors.push(`${font.id}: missing wght.css`);
    variable = { min: Number(wght.min), max: Number(wght.max) };
    family = familyFromCss(pkg, 'wght.css');
    loaders = [['wght', `${pkg}/wght.css`]];
  } else {
    family = meta.family;
    loaders = meta.weights.map((w) => {
      if (!existsSync(join(root, 'node_modules', pkg, `${w}.css`)))
        errors.push(`${font.id}: missing ${w}.css`);
      return [String(w), `${pkg}/${w}.css`];
    });
  }
  if (!family) errors.push(`${font.id}: could not determine the CSS family name`);
  if (typeof font.lineHeight !== 'number' || font.lineHeight < 1.2 || font.lineHeight > 3) {
    errors.push(`${font.id}: lineHeight must be between 1.2 and 3`);
  }

  entries.push({
    id: font.id,
    family,
    pkg,
    names: { ar: font.ar, en: font.en },
    scripts,
    category: font.category,
    weights: meta.weights,
    variable,
    lineHeight: font.lineHeight,
    recommended: Boolean(font.recommended),
    license: meta.license?.type ?? 'unknown',
    attribution: meta.license?.attribution ?? '',
    loaders,
  });
}

if (errors.length) {
  console.error('Font catalog errors:\n  ' + errors.join('\n  '));
  process.exit(1);
}

const q = (value) => JSON.stringify(value);
const lines = [
  '// AUTO-GENERATED by scripts/gen-font-catalog.mjs from scripts/fonts.config.json — do not edit.',
  "import type { CatalogFont } from './catalogTypes';",
  '',
  'export const CATALOG: CatalogFont[] = [',
];
for (const e of entries) {
  lines.push('  {');
  lines.push(`    id: ${q(e.id)},`);
  lines.push(`    family: ${q(e.family)},`);
  lines.push(`    pkg: ${q(e.pkg)},`);
  lines.push(`    names: { ar: ${q(e.names.ar)}, en: ${q(e.names.en)} },`);
  lines.push(`    scripts: ${q(e.scripts)},`);
  lines.push(`    category: ${q(e.category)},`);
  lines.push(`    weights: ${q(e.weights)},`);
  lines.push(`    variable: ${e.variable ? `{ min: ${e.variable.min}, max: ${e.variable.max} }` : 'null'},`);
  lines.push(`    lineHeight: ${e.lineHeight},`);
  lines.push(`    recommended: ${e.recommended},`);
  lines.push(`    license: ${q(e.license)},`);
  lines.push(`    attribution: ${q(e.attribution)},`);
  lines.push('    load: {');
  for (const [key, path] of e.loaders) lines.push(`      ${q(key)}: () => import(${q(path)}),`);
  lines.push('    },');
  lines.push('  },');
}
lines.push('];', '');
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== output) {
    console.error('catalog.generated.ts is out of date. Run `npm run fonts:gen`.');
    process.exit(1);
  }
  console.log(`Font catalog is up to date (${entries.length} fonts).`);
} else {
  writeFileSync(outFile, output);
  console.log(`Wrote ${entries.length} fonts to ${outFile}`);
}
